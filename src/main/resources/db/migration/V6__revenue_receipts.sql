-- Hóa đơn admin quét bằng máy ảnh (Gemini đọc thông tin) và ghi vào báo cáo doanh thu theo ngày.
-- source = SYSTEM_INVOICE: hóa đơn của một đơn đặt phòng trên hệ thống (booking_id có giá trị);
-- source = CASH: khách trả tiền mặt tại khách sạn, chưa có trên hệ thống.
create table if not exists revenue_receipts (
    id bigint generated by default as identity primary key,
    source varchar(20) not null,
    booking_id bigint references bookings (id) on delete set null,
    amount float(53) not null,
    revenue_date date not null,
    receipt_number varchar(100),
    customer_name varchar(255),
    hotel_name varchar(255),
    description varchar(500),
    created_by varchar(255),
    created_at timestamp(6) not null default now()
);

create index if not exists idx_revenue_receipts_date on revenue_receipts (revenue_date);

-- Mỗi đơn đặt phòng chỉ được ghi vào báo cáo một lần
create unique index if not exists uq_revenue_receipts_booking on revenue_receipts (booking_id) where booking_id is not null;
